_keep = []  # Buffers LVGL points to must stay alive


def _addr(data):
    buf = bytearray(data)
    _keep.append(buf)
    return uctypes.addressof(buf)


# Builds an LVGL font in the same format as the built-in fonts.
# The struct layouts match lv_font_fmt_txt.h in LVGL 9.4.
def _create(glyphs, bitmap_b64, builtin):
    first = glyphs[0][0]

    glyph_dsc = bytearray(8)
    for _cp, index, adv, w, h, ox, oy in glyphs:
        glyph_dsc += struct.pack("<IBBbb", index | (adv << 20), w, h, ox, oy)

    unicode_list = b"".join(struct.pack("<H", g[0] - first) for g in glyphs)
    cmap = struct.pack("<IHHIIHHI", first, glyphs[-1][0] - first + 1, 1,
                       _addr(unicode_list), 0, len(glyphs), 0,
                       3)  # Sparse cmap type

    bitmap = binascii.a2b_base64(bitmap_b64)
    # 1 cmap, 8 bits per pixel
    dsc = bytearray(struct.pack("<IIIIHHI", _addr(bitmap), _addr(glyph_dsc),
                                _addr(cmap), 0, 0, 1 | (8 << 9), 0))
    _keep.append(dsc)

    font = lv.font_t()
    font.get_glyph_dsc = builtin.get_glyph_dsc  # LVGL's own drawing functions
    font.get_glyph_bitmap = builtin.get_glyph_bitmap
    font.release_glyph = builtin.release_glyph
    # Room for Å
    ascent = max(builtin.line_height - builtin.base_line,
                 max(g[4] + g[6] for g in glyphs))
    font.line_height = ascent + builtin.base_line
    font.base_line = builtin.base_line
    font.underline_position = builtin.underline_position
    font.underline_thickness = builtin.underline_thickness
    font.dsc = dsc
    font.fallback = builtin  # All other characters come from the built-in font
    return font


normal = lv.font_montserrat_14
title = lv.font_montserrat_28


# Must run after start_board(), when LVGL is initialized
def load():
    global normal, title
    try:
        normal = _create(_GLYPHS_14, _BITMAP_14, lv.font_montserrat_14)
        title = _create(_GLYPHS_28, _BITMAP_28, lv.font_montserrat_28)
    except Exception as err:
        log("Swedish letters not loaded (%r), using built-in fonts" % (err,))
